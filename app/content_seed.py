def _make_templates_for_category(category: str) -> list[dict[str, object]]:
    source_persona = SOURCE_BY_CATEGORY.get(category, "bot")
    tone = "romantic" if source_persona == "nurasyl" else TONE_BY_CATEGORY[category]
    subcategory = SUBCATEGORY_BY_CATEGORY[category]
    count_needed = CONTENT_TEMPLATE_COUNTS[category]
    patterns = NURASYL_PATTERNS[category] if source_persona == "nurasyl" else BOT_PATTERNS[category]
    pools = NURASYL_POOLS if source_persona == "nurasyl" else BOT_POOLS
    texts = _render_texts(count_needed, patterns, pools)

    return [
        {
            "template_id": f"{category}_{index:03d}",
            "category": category,
            "subcategory": subcategory,
            "source_persona": source_persona,
            "tone": tone,
            "text": text,
            "active": True,
            "cooldown_days": 30,
            "weight": 1,
        }
        for index, text in enumerate(texts, start=1)
    ]


def get_content_templates() -> list[dict[str, object]]:
    templates = [
        template
        for category in CONTENT_TEMPLATE_COUNTS
        for template in _make_templates_for_category(category)
    ]
    _validate_templates(templates)
    return templates


def iter_content_templates() -> Iterable[dict[str, object]]:
    return iter(get_content_templates())


def _validate_templates(templates: list[dict[str, object]]) -> None:
    by_category = {category: 0 for category in CONTENT_TEMPLATE_COUNTS}
    template_ids: set[str] = set()
    texts: set[str] = set()

    for template in templates:
        category = str(template["category"])
        text = str(template["text"])
        template_id = str(template["template_id"])

        by_category[category] = by_category.get(category, 0) + 1

        if template_id in template_ids:
            raise RuntimeError(f"Duplicate template_id: {template_id}")
        template_ids.add(template_id)

        if text in texts:
            raise RuntimeError(f"Duplicate content text: {text}")
        texts.add(text)

        lowered = text.lower()
        for term in BANNED_TERMS:
            if term in lowered:
                raise RuntimeError(f"Banned term '{term}' in {template_id}")

        if len([part for part in text.split(".") if part.strip()]) > 3:
            raise RuntimeError(f"Template is too long: {template_id}")

    if by_category != CONTENT_TEMPLATE_COUNTS:
        raise RuntimeError(f"Invalid content counts: {by_category}")


async def seed_content_templates() -> None:
    templates = get_content_templates()
    now = now_utc()

    for template in templates:
        await db.content_templates.update_one(
            {"template_id": template["template_id"]},
            {
                "$set": {
                    **template,
                    "updated_at": now,
                },
                "$setOnInsert": {
                    "created_at": now,
                },
            },
            upsert=True,
        )
