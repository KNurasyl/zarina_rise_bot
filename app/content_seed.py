def _values(index: int, pools: dict[str, list[str]]) -> dict[str, str]:
    data = {}
    cursor = index
    for name, pool in pools.items():
        data[name] = pool[cursor % len(pool)]
        cursor //= len(pool)
    return data


def _render_texts(
    count_needed: int,
    patterns: list[str],
    pools: dict[str, list[str]],
) -> list[str]:
    texts: list[str] = []
    seen: set[str] = set()
    field_names: list[str] = []
    for pattern in patterns:
        for _, field_name, _, _ in Formatter().parse(pattern):
            if field_name and field_name not in field_names:
                field_names.append(field_name)
    active_pools = {field_name: pools[field_name] for field_name in field_names}

    for index in count():
        pattern = patterns[index % len(patterns)]
        base_text = pattern.format(**_values(index // len(patterns), active_pools)).strip()
        candidates = [base_text]
        candidates.extend(f"{base_text} {ending}" for ending in ENDING_POOL)

        for text in candidates:
            if text not in seen:
                seen.add(text)
                texts.append(text)
                break

        if len(texts) == count_needed:
            return texts

        if index > count_needed * 80:
            raise RuntimeError("Not enough unique content variants")

    raise RuntimeError("Unable to generate content variants")


